/* ==========================================================================
   Build the inner pages (about, services, games, updates, contact).

   index.html is the single source of truth for the shared layout: the <head>,
   header, footer, floating buttons and scripts are copied from it into every
   page, so a change to the home page header/footer reaches all pages.

   Page content lives in src/pages/<name>.html:

     <!--
     title: About Us – MY99EXCH
     description: One sentence for search results.
     page: about
     -->
     <main id="main"> … </main>

   Inside a page, <!-- @include cta --> and <!-- @include ribbons --> insert the
   matching home-page sections, so they stay identical everywhere.

   Blog articles live in src/posts/<slug>.html with the same kind of header
   (title, category, icon, image, imageAlt, excerpt, order, optional date
   YYYY-MM-DD). Each becomes blog-<slug>.html, and js/posts-data.js is written
   so the Updates page and "Keep reading" lists can show the cards.

   Run: npm run build:pages   (or npm run build to also rebuild the CSS)
   ========================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pagesDir = path.join(root, 'src/pages');
const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

function slice(html, start, end, label) {
  const a = html.indexOf(start);
  const b = html.indexOf(end, a + start.length);
  if (a === -1 || b === -1) throw new Error(`index.html: could not find ${label}`);
  return html.slice(a, b);
}

// Shared layout pieces from the home page
const head = home.slice(0, home.indexOf('<body'));
const shellTop = slice(home, '<body', '<main id="main">', 'header (<body> … <main id="main">)');
const shellBottom = home.slice(home.indexOf('</main>') + '</main>'.length);

// Home sections that pages can include
const INCLUDES = {
  cta: slice(home, '<section id="join"', '</section>', 'CTA section (#join)') + '</section>',
  ribbons: slice(home, '<div class="ribbons"', '<!-- ═════════', 'marquee ribbons (.ribbons)').trimEnd(),
};

const escapeAttr = v => v.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const idsIn = html => new Set([...html.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]));

// Links like "#faq" in the shared header/footer point at home-page sections.
// On another page they become "index.html#faq" – unless that page has the id too.
function fixLinks(html, ids) {
  return html.replace(/(href|data-fallback)="#([^"]+)"/g, (match, attr, id) =>
    ids.has(id) || id === 'top' || id === 'main' ? match : `${attr}="index.html#${id}"`);
}

function readSource(file, dir) {
  const src = fs.readFileSync(path.join(dir, file), 'utf8');
  const metaMatch = src.match(/^<!--([\s\S]*?)-->/);
  if (!metaMatch) throw new Error(`${file}: missing the <!-- … --> header comment`);
  const meta = Object.fromEntries(metaMatch[1].trim().split('\n').map(line => {
    const i = line.indexOf(':');
    return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
  }));
  return { meta, body: src.slice(metaMatch[0].length).trim() };
}

function requireKeys(file, meta, keys) {
  for (const key of keys) if (!meta[key]) throw new Error(`${file}: missing "${key}" in the header comment`);
}

function writePage(file, meta, main, extraHead = '') {
  main = main.replace(/<!--\s*@include\s+(\w+)\s*-->/g, (m, name) => {
    if (!INCLUDES[name]) throw new Error(`${file}: unknown include "${name}"`);
    return INCLUDES[name];
  });

  const pageHead = head
    .replace(/<title>[\s\S]*?<\/title>/, `<title>${meta.title}</title>`)
    .replace(/(<meta name="description"\s+content=")[^"]*(")/, `$1${escapeAttr(meta.description)}$2`)
    .replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${escapeAttr(meta.title)}$2`)
    .replace(/(<meta property="og:description"\s+content=")[^"]*(")/, `$1${escapeAttr(meta.description)}$2`)
    .replace(/(<meta property="og:type" content=")[^"]*(")/, `$1${meta.ogType || 'website'}$2`)
    .replace(/\s*<link rel="preload"[^>]*>/g, '')
    .replace('</head>', `${extraHead}</head>`)
    .replace('<!DOCTYPE html>', `<!DOCTYPE html>\n<!-- Generated by scripts/build-pages.mjs from ${meta.source} – edit that file, not this one. -->`);

  const ids = new Set([...idsIn(main), ...idsIn(shellTop), ...idsIn(shellBottom)]);
  const top = fixLinks(shellTop, ids).replace(/<body[^>]*>/, `<body data-page="${escapeAttr(meta.page)}">`);
  const bottom = fixLinks(shellBottom, ids);

  fs.writeFileSync(path.join(root, file), `${pageHead}${top}${main}\n${bottom}`);
  console.log(`built ${file}`);
}

/* ---------- Pages ---------- */
for (const file of fs.readdirSync(pagesDir).filter(f => f.endsWith('.html'))) {
  const { meta, body } = readSource(file, pagesDir);
  requireKeys(file, meta, ['title', 'description', 'page']);
  writePage(file, { ...meta, source: `src/pages/${file}` }, body);
}

/* ---------- Blog posts ---------- */
const postsDir = path.join(root, 'src/posts');
const slugify = text => text.toLowerCase().replace(/&amp;/g, 'and').replace(/<[^>]+>/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const escapeHtml = v => String(v).replace(/&(?!amp;|#?\w+;)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const posts = fs.existsSync(postsDir)
  ? fs.readdirSync(postsDir).filter(f => f.endsWith('.html')).map(file => {
      const { meta, body } = readSource(file, postsDir);
      requireKeys(file, meta, ['title', 'category', 'image', 'imageAlt', 'excerpt']);
      const words = body.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
      const slug = file.replace(/\.html$/, '');
      return { file, slug, meta, body, readTime: Math.max(1, Math.round(words / 200)), url: `blog-${slug}.html` };
    }).sort((a, b) => (b.meta.date || '').localeCompare(a.meta.date || '') || Number(a.meta.order || 99) - Number(b.meta.order || 99))
  : [];

for (const post of posts) {
  const { meta } = post;
  // Give every <h2> an id and collect them for the "On this page" list
  const toc = [];
  const body = post.body.replace(/<h2>([\s\S]*?)<\/h2>/g, (m, text) => {
    const id = slugify(text);
    toc.push({ id, text });
    return `<h2 id="${id}">${text}</h2>`;
  });
  const dateHtml = meta.date
    ? `<span class="post-dot" aria-hidden="true"></span><time datetime="${meta.date}">${new Date(`${meta.date}T00:00:00Z`).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' })}</time>`
    : '';
  const structured = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: meta.title.replace(/&amp;/g, '&'),
    description: meta.excerpt,
    image: meta.image,
    author: { '@type': 'Organization', name: 'MY99EXCH' },
    publisher: { '@type': 'Organization', name: 'MY99EXCH' },
    ...(meta.date ? { datePublished: meta.date } : {}),
  };

  const main = `<main id="main">
    <article>
      <!-- ═════════ Article hero ═════════ -->
      <header class="page-hero has-watermark">
        <div class="hero-lighting" aria-hidden="true">
          <span class="hero-beam right-0 top-[16%] w-[55%]"></span>
          <span class="hero-beam right-0 top-[28%] w-[38%] opacity-60"></span>
        </div>
        <span class="section-watermark wm-top-right" data-drift="-0.12" aria-hidden="true">MY99EXCH</span>

        <div class="wrap page-hero-grid">
          <div data-reveal="left" class="reveal">
            <nav class="breadcrumb" aria-label="Breadcrumb">
              <a href="index.html">Home</a><i data-icon="chevron-right"></i><a href="updates.html">Updates</a><i data-icon="chevron-right"></i><span aria-current="page" class="line-clamp-1">${meta.title}</span>
            </nav>
            <span class="post-cat mt-6"><i data-icon="${escapeHtml(meta.icon || 'sparkles')}"></i> ${escapeHtml(meta.category)}</span>
            <h1 class="t-page t-article mt-5">${meta.title}</h1>
            <p class="t-lead mt-5 max-w-[36rem]">${escapeHtml(meta.excerpt)}</p>
            <div class="article-meta mt-7">
              <span class="article-avatar" aria-hidden="true">M</span>
              <span><span class="block font-semibold text-snow">MY99EXCH Team</span><span class="flex flex-wrap items-center gap-x-2.5"><span>${post.readTime} min read</span>${dateHtml}</span></span>
            </div>
          </div>
          <div data-reveal="right" class="reveal">
            <figure class="media-frame article-cover">
              <img src="${meta.image}" alt="${escapeHtml(meta.imageAlt)}" fetchpriority="high">
              <span class="tag"><i data-icon="${escapeHtml(meta.icon || 'sparkles')}"></i> ${escapeHtml(meta.category)}</span>
            </figure>
          </div>
        </div>
      </header>

      <!-- ═════════ Article body ═════════ -->
      <div class="section">
        <div class="wrap article-layout">
          <div class="prose-article reveal">
${body.split('\n').map(l => '            ' + l).join('\n')}
          </div>

          <aside class="article-aside" aria-label="Article tools">
            <nav class="card toc p-5" aria-label="On this page">
              <p class="eyebrow">On this page</p>
              <ul class="mt-4">
${toc.map(t => `                <li><a href="#${t.id}" data-toc-link>${t.text}</a></li>`).join('\n')}
              </ul>
            </nav>
            <div class="card p-5">
              <p class="eyebrow">Share</p>
              <div class="mt-4 flex flex-wrap gap-2.5">
                <button type="button" class="chip-link" data-share="copy"><i data-icon="link"></i> <span data-share-label>Copy link</span></button>
                <a href="#" class="chip-link" data-share="whatsapp" target="_blank" rel="noopener"><i data-brand="whatsapp"></i> WhatsApp</a>
              </div>
            </div>
            <div class="card article-cta p-6">
              <span class="icon-circle h-12 w-12"><i data-icon="crown"></i></span>
              <h2 class="mt-4 font-display text-lg font-semibold">Ready to play?</h2>
              <p class="t-small mt-1">Create your account and explore the games.</p>
              <a href="#join" data-route="register" class="btn btn-primary btn-sm mt-5 w-full">Register Now <i data-icon="arrow-right" class="icon-arrow"></i></a>
            </div>
          </aside>
        </div>
      </div>
    </article>

    <!-- ═════════ Keep reading (cards from js/posts-data.js) ═════════ -->
    <section class="section bg-band">
      <div class="wrap">
        <div class="flex flex-col gap-6 md:flex-row md:items-end md:justify-between">
          <div class="section-head reveal">
            <p class="eyebrow">Keep reading</p>
            <h2 class="t-h2">More from <span class="text-gold-grad">MY99EXCH</span></h2>
          </div>
          <a href="updates.html" class="btn btn-secondary shrink-0 self-start md:self-auto"><i data-icon="layout-grid"></i> All Updates</a>
        </div>
        <ul class="blog-grid mt-10 md:mt-12" data-related="${post.slug}" aria-label="Related articles"></ul>
      </div>
    </section>

    <!-- @include cta -->
  </main>`;

  writePage(post.url, {
    title: `${meta.title} – MY99EXCH`,
    description: meta.excerpt,
    page: 'updates',
    ogType: 'article',
    source: `src/posts/${post.file}`,
  }, main, `  <script type="application/ld+json">${JSON.stringify(structured)}</script>\n`);
}

// Card data for the Updates page and related lists
const data = posts.map(p => ({
  slug: p.slug, url: p.url, title: p.meta.title, category: p.meta.category, icon: p.meta.icon || 'sparkles',
  image: p.meta.image, excerpt: p.meta.excerpt, readTime: p.readTime, ...(p.meta.date ? { date: p.meta.date } : {}),
}));
fs.writeFileSync(path.join(root, 'js/posts-data.js'),
  `/* Generated by scripts/build-pages.mjs from src/posts/ – do not edit by hand. */\nconst POSTS = ${JSON.stringify(data, null, 2)};\n`);
console.log(`wrote js/posts-data.js (${data.length} posts)`);
